"""Настройки на приложението. Всички ограничения се променят само тук."""

from pathlib import Path

# Папки на проекта
BASE_DIR = Path(__file__).resolve().parent.parent
VOICES_DIR = BASE_DIR / "voices"
STATIC_DIR = BASE_DIR / "static"

# Максимална дължина на поставения текст (в знаци).
# Около 10 000 знака са приблизително 10 минути звук.
